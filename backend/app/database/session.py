"""
Sesión SQLAlchemy y dependencia FastAPI `get_db`.

El motor apunta a DATABASE_URL (PostgreSQL por defecto). Para pruebas locales
sin PostgreSQL se puede usar:  DATABASE_URL=sqlite:///./sl_translator.db
"""

from __future__ import annotations

from collections.abc import Generator

from sqlalchemy import create_engine
from sqlalchemy.orm import Session, sessionmaker

from app.core.config import settings

engine = create_engine(
    settings.DATABASE_URL,
    pool_pre_ping=True,
    future=True,
)

SessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine, future=True)


def get_db() -> Generator[Session, None, None]:
    """Dependencia de FastAPI que entrega una sesión y la cierra al terminar."""
    db = SessionLocal()
    try:
        yield db
    finally:
        db.close()